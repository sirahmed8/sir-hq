"""Writes plans/MAIN_PLAN.md (the one page every project chat reads) and the message bus files in ops/bus/.
Run: python D:/Projects/_SIR/plans/generate_main_plan.py   (after wave_study.py and generate_kit.py)"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from products import PRODUCTS  # noqa: E402

BUS = "D:/Projects/_SIR/ops/bus"
PROVIDES = {
    "sir-platform": "owner-auth, signed-webhook, ai-proxy, billing fallback, legal pack, tokens and ui kit, i18n and settings, sir-kit CLI",
    "sir-ai": "the AI gateway idea that became the Platform ai-proxy; local assistant",
    "sir-laptop-manager": "agent-config sync, local RAG, routines, workspace health report",
    "sir-portfolio": "the public product wall; shows real statuses of every product",
    "sir-jobs": "income engine: paid freelance and remote work leads",
    "ahome": "nothing: private, isolated, no data to or from any other project",
}
NEEDS = "the Cloudflare and Firebase logins; shared concerns (owner-auth, signed-webhook, billing fallback, ai-proxy, legal pack, tokens and UI) are kept as internal packages in each product and extracted into SIR Platform last"


def main():
    rows = sorted(PRODUCTS, key=lambda p: (p["wave"], p["slug"]))
    table = "\n".join(f"| {p['wave']} | {p['display']} | `{p['folder']}` | {PROVIDES.get(p['slug'], '(consumes the shared kit)')} |" for p in rows)
    text = f"""# MAIN PLAN (the page every SIR chat reads; generated by plans/generate_main_plan.py, edit the data not this file)

## Goal
Rebuild every product from scratch as a premium, production-hosted SIR project, in a studied order: AHome first, then what earns money, then the rest. First income milestone: 1,200 EGP. HQ prepares and keeps this plan; one chat per project folder builds.

## Order and what each project gives the others
| Wave | Project | Folder | Provides |
|---|---|---|---|
{table}

All web products need: {NEEDS}. SIR Platform and SIR Portfolio are built last, from the finished products.

## How every project chat works
1. Read `D:/Projects/_SIR/NEXT.md`, this file, your project's `.sir/CHECKPOINT.md` and `.sir/TASKS.md`; your first task is a deep scan of `legacy/` and the plan, then you improve the plan.
2. Your project folder has the kit: PLAN, TASKS, BOARD, ARCHITECTURE, DESIGN, PLATFORMS, PRODUCTION, QUALITY, BENCHMARK, TEAM, TOOLKIT. Use your sub-agents (TEAM.md) and tools (TOOLKIT.md); install more when they help, vetted, free.
3. Use the computer for any task: `plans/COMPUTER_USE.md`. Work out how yourself; never hand Ahmed steps.
4. Commit and push straight to `main` when `verify` passes. No pull requests. Never delete `legacy/`.
5. Talk to other projects: durable messages in `D:/Projects/_SIR/ops/bus/<slug>.md` (see `ops/bus/README.md`), live with ListAgents and SendMessage. Ask for what you need from a project that provides it; tell a project when you change something it depends on.
6. Dashboards: `D:/Projects/_SIR/mods` holds Ahmed's dashboard mods (SIR Control Room, SIR Context, SIR Guards). Improve them when something is missing, or add a pane or dashboard for your project as a new mod there (register it in `.claude-plugin/marketplace.json`, `claude plugin install <name>@sir-mods`). Keep the shared ones generic.
7. End: update `.sir/CHECKPOINT.md` (Now, Next step with the exact command, Open promises, Re-read), one line in `_SIR/ops/MISSION_LOG.md`, push.

## Privacy and safety lines
AHome and everything about Habiba never leave AHome. API keys may be created, rotated and deleted by agents; no secrets in git. Owner-only checks run on the server. Only Ahmed: sign-in, passkey and 2FA, CAPTCHA, payments, typing secrets into forms.
"""
    io.open(os.path.join(HERE, "MAIN_PLAN.md"), "w", encoding="utf-8", newline="\n").write(text)
    os.makedirs(BUS, exist_ok=True)
    readme = """# Message bus between projects (durable; live talk uses ListAgents and SendMessage)

One file per project: `ops/bus/<slug>.md` is that project's inbox. To message a project, append a line to its file:
`- [ ] 2026-10-30 from sir-platform: owner-auth 0.2 is published; change `verifyOwner(token)` to `verifyOwner(token, opts)`.`
The owner of the inbox ticks `[x]` when handled and may add a reply line starting `  reply:`. Keep messages short and actionable; say what you need, by when, and where the details are. The SIR Control Room pane and the status line show unread counts. `ops/bus/all.md` is for notices to every project.
"""
    io.open(os.path.join(BUS, "README.md"), "w", encoding="utf-8", newline="\n").write(readme)
    for p in PRODUCTS + [dict(slug="all", display="all projects")]:
        f = os.path.join(BUS, p["slug"] + ".md")
        if not os.path.exists(f):
            io.open(f, "w", encoding="utf-8", newline="\n").write(f"# Inbox: {p['display']}\nNewest first. Format and rules: README.md\n")
    print("MAIN_PLAN.md and", len(PRODUCTS) + 1, "inboxes")


if __name__ == "__main__":
    main()
