#!/usr/bin/env node
// Sync canonical AGENTS.md to thin agent pointers (CLAUDE.md, GEMINI.md, etc.)
// Spec: _SIR/plans/MEMORY_AND_SYNC_SYSTEM.md section 2
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const SIR_ROOT = path.resolve(HERE, '..', '..');
export const WORKSPACE_ROOT = path.dirname(SIR_ROOT);

export const MARKER = '<!-- Generated by _SIR/scripts/agent-config/sync-agent-files.mjs. Do not edit directly; edit AGENTS.md. -->';

export function getExpectedContent(tool) {
  if (tool === 'CLAUDE.md') {
    return `${MARKER}\n@AGENTS.md\n\nRead AGENTS.md completely first, then .sir/CHECKPOINT.md.\n`;
  }
  return `${MARKER}\nRead AGENTS.md completely first, then .sir/CHECKPOINT.md.\n`;
}

export function getProjectDirs(workspace = WORKSPACE_ROOT) {
  const dirs = [];
  try {
    const entries = fs.readdirSync(workspace, { withFileTypes: true });
    for (const ent of entries) {
      if (!ent.isDirectory() || ent.name.startsWith('.') || ent.name.startsWith('_')) continue;
      const full = path.join(workspace, ent.name);
      const hasSir = fs.existsSync(path.join(full, '.sir'));
      const hasAgents = fs.existsSync(path.join(full, 'AGENTS.md'));
      if (hasSir || hasAgents) {
        dirs.push(full);
      }
    }
  } catch {
    // return empty if workspace cannot be read
  }
  return dirs;
}

export function inspectProjectPointers(projectDir) {
  const issues = [];
  const targets = [
    { file: 'CLAUDE.md', tool: 'CLAUDE.md' },
    { file: 'GEMINI.md', tool: 'GEMINI.md' },
  ];

  if (fs.existsSync(path.join(projectDir, '.codex'))) {
    targets.push({ file: path.join('.codex', 'AGENTS.md'), tool: 'codex' });
  }
  if (fs.existsSync(path.join(projectDir, '.opencode'))) {
    targets.push({ file: path.join('.opencode', 'OPENCODE.md'), tool: 'opencode' });
  }
  if (fs.existsSync(path.join(projectDir, '.kilo'))) {
    targets.push({ file: path.join('.kilo', 'KILO.md'), tool: 'kilo' });
  }

  for (const t of targets) {
    const filePath = path.join(projectDir, t.file);
    const expected = getExpectedContent(t.tool);
    if (!fs.existsSync(filePath)) {
      issues.push({ path: filePath, type: 'missing', expected });
      continue;
    }
    const current = fs.readFileSync(filePath, 'utf8');
    const normCur = current.replace(/\r\n/g, '\n').trim();
    const normExp = expected.replace(/\r\n/g, '\n').trim();
    if (normCur !== normExp) {
      issues.push({ path: filePath, type: 'divergent', current, expected });
    }
  }
  return issues;
}

export function writeProjectPointers(projectDir, dryRun = false) {
  const issues = inspectProjectPointers(projectDir);
  const actions = [];

  for (const issue of issues) {
    if (dryRun) {
      actions.push({ action: 'would_write', path: issue.path, reason: issue.type });
      continue;
    }
    // Backup if divergent
    if (issue.type === 'divergent' && fs.existsSync(issue.path)) {
      const backupDir = path.join(projectDir, '.sir', 'backups', 'agent-pointers');
      fs.mkdirSync(backupDir, { recursive: true });
      const backupFile = path.join(backupDir, `${path.basename(issue.path)}.${Date.now()}.bak`);
      fs.copyFileSync(issue.path, backupFile);
    }
    fs.mkdirSync(path.dirname(issue.path), { recursive: true });
    fs.writeFileSync(issue.path, issue.expected, 'utf8');
    actions.push({ action: 'wrote', path: issue.path, reason: issue.type });
  }
  return actions;
}

export function inspectGlobalPointers() {
  const home = process.env.USERPROFILE || process.env.HOME || 'C:\\Users\\a7med';
  const globals = [
    { name: 'claude', path: path.join(home, '.claude', 'CLAUDE.md') },
    { name: 'gemini', path: path.join(home, '.gemini', 'GEMINI.md') },
    { name: 'codex', path: path.join(home, '.codex', 'AGENTS.md') },
  ];
  const results = [];
  for (const g of globals) {
    const exists = fs.existsSync(g.path);
    const content = exists ? fs.readFileSync(g.path, 'utf8') : '';
    const pointsWorkspace = content.includes('D:\\Projects\\AGENTS.md');
    const pointsStartAny = content.includes('START_ANY_AI.md');
    results.push({ ...g, exists, pointsWorkspace, pointsStartAny, content });
  }
  return results;
}

export function writeGlobalDiffReport(globalResults, reportPath) {
  const lines = ['# Global User Pointers Audit Diff', '', `Date: ${new Date().toISOString()}`, ''];
  for (const g of globalResults) {
    lines.push(`## ${g.name} (${g.path})`);
    lines.push(`- Exists: ${g.exists}`);
    lines.push(`- Points to D:\\Projects\\AGENTS.md: ${g.pointsWorkspace}`);
    lines.push(`- Points to START_ANY_AI.md: ${g.pointsStartAny}`);
    lines.push('### Planned canonical content:');
    lines.push('```markdown');
    lines.push(`${MARKER}`);
    lines.push('# Global rules');
    lines.push('Everything binding for this machine lives in the workspace, not in this file.\n');
    lines.push('1. Read `D:\\Projects\\AGENTS.md` (workspace laws) and `D:\\Projects\\_SIR\\START_ANY_AI.md` at the start of every session.');
    lines.push('2. In a project folder read that project\'s `AGENTS.md`, then `.sir/CHECKPOINT.md`, and continue from "Next step".');
    lines.push('```\n');
  }
  fs.mkdirSync(path.dirname(reportPath), { recursive: true });
  fs.writeFileSync(reportPath, lines.join('\n'), 'utf8');
}

export function runSync(options = {}) {
  const mode = options.check ? 'check' : options.write ? 'write' : 'dry-run';
  const projects = getProjectDirs(options.workspace || WORKSPACE_ROOT);
  let totalIssues = 0;
  const reports = [];

  for (const p of projects) {
    const pName = path.basename(p);
    const issues = inspectProjectPointers(p);
    totalIssues += issues.length;

    if (mode === 'write') {
      const actions = writeProjectPointers(p, false);
      reports.push({ project: pName, issues, actions });
    } else {
      reports.push({ project: pName, issues });
    }
  }

  // Audit global pointers
  const globalAudit = inspectGlobalPointers();
  const dateStr = new Date().toISOString().slice(0, 10);
  const diffReportPath = path.join(SIR_ROOT, 'ops', 'reports', `global-pointers-diff-${dateStr}.md`);
  writeGlobalDiffReport(globalAudit, diffReportPath);

  return { mode, projectsCount: projects.length, totalIssues, reports, globalAudit, diffReportPath };
}

function main() {
  const args = process.argv.slice(2);
  const isCheck = args.includes('--check');
  const isWrite = args.includes('--write');

  const result = runSync({ check: isCheck, write: isWrite });

  console.log(`sync-agent-files [mode=${result.mode}]: checked ${result.projectsCount} projects.`);
  if (result.totalIssues > 0) {
    console.log(`Found ${result.totalIssues} pointer issues across projects:`);
    for (const r of result.reports) {
      if (r.issues && r.issues.length > 0) {
        console.log(`  Project ${r.project}:`);
        for (const iss of r.issues) {
          console.log(`    - [${iss.type}] ${iss.path}`);
        }
      }
    }
  } else {
    console.log('All project agent pointers are in sync with AGENTS.md.');
  }

  console.log(`Global pointers status audited. Diff report written to: ${result.diffReportPath}`);

  if (isCheck && result.totalIssues > 0) {
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main();
}
