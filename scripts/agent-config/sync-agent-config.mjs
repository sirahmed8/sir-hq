// Writes each tool's native copy from this folder. Never hand-edit the generated copies.
//   Codex, Antigravity, OpenCode, Kilo: skills in D:\Projects\.agents\skills (project scope, same folder they all read)
//   Claude Code (only with --claude): agents in D:\Projects\.claude\agents; the same roster already lives in ~/.claude/agents
// Global installs (~/.codex, ~/.gemini, ~/.claude) are left to the owner; see _SIR/ops/OWNER_ACTIONS.md.
import { cpSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const workspace = process.argv[2] ?? 'D:/Projects';
const targets = [
  { from: 'skills', to: join(workspace, '.agents', 'skills') },
  ...(process.argv.includes('--claude') ? [{ from: 'agents', to: join(workspace, '.claude', 'agents') }] : []),
];
// Overwrites files in place and never deletes: remove a retired skill by hand.
for (const t of targets) {
  mkdirSync(t.to, { recursive: true });
  cpSync(join(here, t.from), t.to, { recursive: true });
  const n = readdirSync(t.to).length;
  console.log(`${t.from} -> ${t.to} (${n} entries)`);
}
writeFileSync(join(workspace, '.agents', 'GENERATED.txt'),
  'Generated by Laptop manager/agent-config/sync-agent-config.mjs. Edit the source folder, not these copies.\n');
