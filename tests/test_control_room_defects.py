# tests/test_control_room_defects.py
"""Browser test for the Control Room page.

The page is generated by plans/generate_dashboard.py into ops/artifact/control-room.html and copied
byte for byte to ops/public/dashboard.html, which is the page the local server serves at
/dashboard.html. This test opens that page at 320/390/768/1280 px in light and dark, walks every
view and asserts: no horizontal scroll, no clipped text, one label per destination, and numbers
that come from the data instead of being invented.

Requires Playwright with a Chromium build. It skips (never fails) when Playwright, Node.js or the
browser is missing, so the suite stays green on a machine that has none of them.
"""
import json
import os
import pathlib

import pytest

from playwright_support import chromium_ready, node_path

_NODE = node_path()
if _NODE:
    os.environ.setdefault("PLAYWRIGHT_NODEJS_PATH", _NODE)

try:
    from playwright.sync_api import sync_playwright
except Exception:  # playwright absent
    sync_playwright = None

PAGE = pathlib.Path("ops/public/dashboard.html").resolve()
VIEWS = ["now", "projects", "tools", "checks", "ideas", "owner", "accounts"]
WIDTHS = [320, 390, 768, 1280]
THEMES = ["light", "dark"]
RETIRED_LABELS = ["Gemini Handover", "CI & Remote"]
PLACEHOLDER_TEXT = ["undefined", "NaN", "[object Object]", "TODO"]


def _skip_reason():
    if sync_playwright is None:
        return "Playwright is not installed"
    if not PAGE.is_file():
        return f"{PAGE.name} is not generated yet; run python plans/generate_dashboard.py"
    if not _NODE and os.name == "nt":
        return "Node.js was not found; Playwright needs it on Windows"
    return ""


def _browser_ready():
    """True when Chromium can actually start here."""
    return chromium_ready()


def _open(browser):
    """Open the page, muted and headless, and return the page."""
    page = browser.new_page()
    page.goto(PAGE.as_uri(), wait_until="networkidle")
    page.evaluate("() => { window.speechSynthesis.speak = () => {}; }")
    return page


def _set_view(page, view):
    page.evaluate("v => window.setView(v)", view)
    page.wait_for_timeout(60)


def _apply_theme(page, theme):
    page.evaluate(f'document.documentElement.dataset.theme = "{theme}"')
    page.wait_for_timeout(30)


def test_no_horizontal_scroll_all_widths_themes():
    reason = _skip_reason()
    if reason:
        pytest.skip(reason)
    if not _browser_ready():
        pytest.skip("Chromium is not installed for Playwright")
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, args=["--mute-audio"])
        try:
            page = _open(browser)
            try:
                for width in WIDTHS:
                    page.set_viewport_size({"width": width, "height": 900})
                    for theme in THEMES:
                        _apply_theme(page, theme)
                        for view in VIEWS:
                            _set_view(page, view)
                            overflow = page.evaluate(
                                "() => document.documentElement.scrollWidth > document.documentElement.clientWidth || "
                                "document.body.scrollWidth > document.body.clientWidth"
                            )
                            assert not overflow, f"horizontal scroll in {view} at {width}px {theme}"
            finally:
                page.close()
        finally:
            browser.close()


def test_no_clipped_text():
    reason = _skip_reason()
    if reason:
        pytest.skip(reason)
    if not _browser_ready():
        pytest.skip("Chromium is not installed for Playwright")
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, args=["--mute-audio"])
        try:
            page = _open(browser)
            try:
                for width in WIDTHS:
                    page.set_viewport_size({"width": width, "height": 900})
                    for theme in THEMES:
                        _apply_theme(page, theme)
                        for view in VIEWS:
                            _set_view(page, view)
                            clipped = page.evaluate(
                                "() => Array.from(document.querySelectorAll('h1,h2,h3,p,span,li,td')).filter(el => "
                                "el.scrollWidth > el.clientWidth + 1 || el.scrollHeight > el.clientHeight + 1)"
                                ".map(el => el.tagName + ':' + (el.textContent || '').slice(0, 40))"
                            )
                            assert not clipped, f"clipped text in {view} at {width}px {theme}: {clipped[:5]}"
            finally:
                page.close()
        finally:
            browser.close()


def test_one_label_per_destination():
    reason = _skip_reason()
    if reason:
        pytest.skip(reason)
    if not _browser_ready():
        pytest.skip("Chromium is not installed for Playwright")
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, args=["--mute-audio"])
        try:
            page = _open(browser)
            try:
                labels = page.evaluate(
                    "() => Array.from(document.querySelectorAll('#nav-bottom [data-view] span:first-child'))"
                    ".map(el => el.textContent.trim())"
                )
                assert labels, "the bottom navigation must have entries"
                assert len(labels) == len(set(labels)), f"duplicate navigation labels: {labels}"
                body = page.content()
                for retired in RETIRED_LABELS:
                    assert retired not in body, f"retired duplicate name '{retired}' is still on the page"
            finally:
                page.close()
        finally:
            browser.close()


def test_numbers_come_from_the_data():
    reason = _skip_reason()
    if reason:
        pytest.skip(reason)
    if not _browser_ready():
        pytest.skip("Chromium is not installed for Playwright")
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, args=["--mute-audio"])
        try:
            page = _open(browser)
            try:
                payload = json.loads(page.evaluate("() => JSON.stringify(D)"))
                notes = payload.get("notes") or {}
                suggestions = notes.get("suggestions") or {}
                expected = {
                    "now": len(payload.get("team") or []),
                    "projects": len(payload.get("projects") or []),
                    "tools": len(payload.get("pool") or []),
                    "checks": len(payload.get("rounds") or []),
                    "ideas": (suggestions.get("counts") or {}).get("pending", 0),
                    "owner": len(notes.get("owner_actions") or []),
                    "accounts": 0,
                }
                rendered = page.evaluate(
                    "() => { const out = {}; document.querySelectorAll('#nav-bottom [data-view]').forEach(b => {"
                    "const c = b.querySelector('.count'); out[b.getAttribute('data-view')] = c ? Number(c.textContent.trim()) : null; });"
                    "return out; }"
                )
                assert rendered == expected, f"navigation counts do not match the data: {rendered} vs {expected}"

                for view in VIEWS:
                    _set_view(page, view)
                    text = page.evaluate("() => document.getElementById('view').innerText")
                    for junk in PLACEHOLDER_TEXT:
                        assert junk not in text, f"placeholder text '{junk}' in the {view} view"
            finally:
                page.close()
        finally:
            browser.close()
